import { readFileSync } from 'node:fs';

// The six primary links live in components/shared/nav-links.ts (single source of truth).
// Read their hrefs from that file so the drawer filter can never drift from the header.
function primaryHrefs() {
  // Resolved from the project root (cwd), like tools/write-nav-config.mjs and vitest.
  const src = readFileSync('components/shared/nav-links.ts', 'utf8');
  return [...src.matchAll(/href:\s*'([^']+)'/g)].map((m) => m[1]);
}

export function buildNavConfig(i) {
  const signIn = (i.signInMenu ?? []).filter((it) => typeof it.label === 'string' && it.label.trim() !== '' && it.href);

  // The drawer renders the primary links, the sign-in items and its own Try Demo button,
  // so DRAWER_LINKS keeps only links that are not already shown elsewhere.
  const taken = new Set([...primaryHrefs(), ...signIn.map((it) => it.href), '/try-demo']);
  const drawer = (i.drawerLinks ?? []).filter((it) => it.href && !taken.has(it.href));

  const list = (name, items) =>
    `export const ${name}: readonly { label: string; href: string }[] = ${JSON.stringify(items, null, 2)};\n`;
  const bg = i.headerScrolled?.background ?? 'rgba(255, 255, 255, 0.72)';
  return (
    '// Generated by tools/write-nav-config.mjs from reference/interactions.json.\n' +
    list('SIGN_IN_ITEMS', signIn) +
    list('DRAWER_LINKS', drawer) +
    `export const HEADER_SCROLLED_BG = ${JSON.stringify(bg)};\n` +
    `export const HEADER_BG_IMAGE = ${JSON.stringify(i.headerTop?.backgroundImage ?? 'none')};\n`
  );
}
